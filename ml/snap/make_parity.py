"""Write web/test/fixtures/parity.json (+ 4 small jpgs) from the shipped models and the Python pipeline.

    python ml/snap/make_parity.py
Each fixture image is downscaled to a short side of 192 px (<256, so the CLIP resize is an upscale = no antialias ambiguity), saved as
JPEG, then re-decoded with PIL; the raw RGB of THAT decode goes into the json so node does not need an image decoder.
"""
import base64, json, sys
import numpy as np
import onnxruntime as ort
from PIL import Image
from common import MODELS, ROOT, SP
from snaplib import clip_prep, letterbox, decode_locator

FX = ROOT / "web" / "test" / "fixtures"; FX.mkdir(parents=True, exist_ok=True)
clip = json.loads((MODELS / "clip.json").read_text(encoding="utf-8")); loc = json.loads((MODELS / "locator.json").read_text(encoding="utf-8"))
vocab = json.loads((MODELS / "vocab.json").read_text(encoding="utf-8"))
M = np.frombuffer((MODELS / "vocab_emb.bin").read_bytes(), dtype="<f2").astype(np.float32).reshape(len(vocab), -1)
ids = [v["id"] for v in vocab]


def small(src, name, short=192):
    im = Image.open(src).convert("RGB"); r = short / min(im.size)
    im = im.resize((round(im.width * r), round(im.height * r)), Image.BILINEAR); im.save(FX / name, quality=90)
    a = np.asarray(Image.open(FX / name).convert("RGB")); return a


cs = ort.InferenceSession(str(MODELS / "clip_image.onnx"), providers=["CPUExecutionProvider"])
ls = ort.InferenceSession(str(MODELS / "locator.onnx"), providers=["CPUExecutionProvider"])
SRC = [(SP / "foodimg/lu_rou_fan_2.jpg", "snap_lurou.jpg"), (SP / "eval/drinks/bubble_tea_1.jpg", "snap_bubbletea.jpg"),
       (SP / "negatives/paper_cups_crop.jpg", "snap_papercups.jpg")]
out = dict(note="generated by ml/snap/make_parity.py; rgb_b64 = raw interleaved RGB uint8 decoded by PIL from the jpg beside this file", images=[])
for src, name in SRC:
    a = small(src, name); h, w, _ = a.shape
    x = clip_prep(Image.fromarray(a), clip["size"], clip["resize"], clip["crop"])
    e = cs.run(None, {clip["input"]: x[None].astype(np.float32)})[0][0]; e = e / np.linalg.norm(e)
    sims = M @ e; top4 = np.argsort(-sims)[:4]; top = top4[:3]; gap = float(min(sims[top4[i]] - sims[top4[i + 1]] for i in range(3)))
    pick = [ids[int(top[0])], ids[int(top[1])], next(i for i in ids if i.startswith("neg_empty_cup"))]
    out["images"].append(dict(file=name, w=int(w), h=int(h), rgb_b64=base64.b64encode(a.tobytes()).decode(), input_first8=[float(v) for v in x.reshape(-1)[:8]],
                              embedding_first8=[float(v) for v in e[:8]], embedding_full=[round(float(v), 6) for v in e],
                              vocab_cos=[dict(id=i, cos=float(sims[ids.index(i)])) for i in pick], top3=[ids[int(t)] for t in top], top3_min_gap=gap))
# locator image: a multi-item UEC plate scene
a = small(SP / "research/r4/data/28.jpg", "snap_locator.jpg", short=240); h, w, _ = a.shape
lx, r, px, py = letterbox(Image.fromarray(a), loc["imgsz"])
raw = ls.run(None, {loc["input"]: lx})[0][0]
boxes = decode_locator(raw, len(loc["classes"]), r, px, py, w, h, loc["conf"], loc["iou"], loc["contain"], loc["max_det"])
out["locator"] = dict(file="snap_locator.jpg", w=int(w), h=int(h), rgb_b64=base64.b64encode(a.tobytes()).decode(),
                      boxes=[dict(box=[round(float(v), 2) for v in b["box"]], score=round(b["score"], 4), name=loc["classes"][b["cls"]]["name"], food=loc["classes"][b["cls"]]["food"]) for b in boxes])
(FX / "parity.json").write_text(json.dumps(out), encoding="utf-8")
print("wrote parity.json", (FX / "parity.json").stat().st_size // 1024, "KB; locator boxes:", [(b["name"], b["box"]) for b in out["locator"]["boxes"]])
